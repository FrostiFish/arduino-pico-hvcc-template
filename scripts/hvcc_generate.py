Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

import hashlib
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

PROJECT_DIR = Path(env["PROJECT_DIR"])        # noqa: F821
PD_DIR      = PROJECT_DIR / "pd"
LIB_ROOT    = PROJECT_DIR / "lib"
STAMP_NAME  = ".pd_hash"
KEEP_FILES  = {"library.json"}                # survives regeneration


def fail(msg):
    print(f"[hvcc] ERROR: {msg}")
    env.Exit(1)                               # noqa: F821


def find_patch():
    patches = sorted(PD_DIR.glob("*.pd"))     # top level only
    if not patches:
        print(f"[hvcc] no .pd file in {PD_DIR}, skipping generation")
        return None
    if len(patches) > 1:
        names = ", ".join(p.name for p in patches)
        fail(f"multiple .pd files in pd/ ({names}). Keep one main patch "
             "at the top level and move abstractions into a subfolder.")
    return patches[0]


def patch_name(patch):
    # hvcc uses the name in C identifiers (Heavy_<name>.hpp)
    name = re.sub(r"\W", "_", patch.stem)
    return f"_{name}" if name[0].isdigit() else name


def wanted_hvcc_version():
    """Pinned version from platformio.ini (custom_hvcc_version), or ''."""
    return env.GetProjectOption("custom_hvcc_version", "").strip()  # noqa: F821


def hash_inputs(name):
    h = hashlib.sha256(f"{name}|{wanted_hvcc_version()}".encode())
    for f in sorted(PD_DIR.rglob("*")):
        if f.is_file():
            h.update(str(f.relative_to(PD_DIR)).encode())
            h.update(f.read_bytes())
    return h.hexdigest()


def remove_stale_libs(current_dir):
    """Remove Heavy_* libs generated by this script for an older patch name."""
    for d in LIB_ROOT.glob("Heavy_*"):
        if d.is_dir() and d != current_dir and (d / STAMP_NAME).exists():
            print(f"[hvcc] removing stale library {d.name}")
            shutil.rmtree(d)


def installed_hvcc_version(python):
    r = subprocess.run(
        [python, "-c",
         "import importlib.metadata as m; print(m.version('hvcc'))"],
        capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def ensure_hvcc():
    python = env.subst("$PYTHONEXE")              # noqa: F821
    wanted = wanted_hvcc_version()
    installed = installed_hvcc_version(python)
    if installed and (not wanted or installed == wanted):
        return
    spec = f"hvcc=={wanted}" if wanted else "hvcc"
    print(f"[hvcc] installing {spec} (found: {installed or 'none'})...")
    result = subprocess.run([python, "-m", "pip", "install", spec],
                            capture_output=True, text=True)
    print(result.stdout)
    if result.returncode != 0:
        print(result.stderr)
        fail(f"could not install {spec}, try installing it manually")


def hvcc_command():
    python = Path(env.subst("$PYTHONEXE"))    # noqa: F821
    for exe in ("hvcc", "hvcc.exe"):
        candidate = python.parent / exe
        if candidate.exists():
            return [str(candidate)]
    return [str(python), "-m", "hvcc"]


def generate():
    patch = find_patch()
    if patch is None:
        return
    name = patch_name(patch)

    lib_dir = LIB_ROOT / f"Heavy_{name}"
    stamp   = lib_dir / STAMP_NAME

    remove_stale_libs(lib_dir)

    current = hash_inputs(name)
    if stamp.exists() and stamp.read_text().strip() == current:
        print(f"[hvcc] {patch.name} unchanged, skipping")
        return

    ensure_hvcc()
    print(f"[hvcc] generating C++ from {patch.name} -> lib/{lib_dir.name}")
    with tempfile.TemporaryDirectory() as tmp:
        cmd = hvcc_command() + [
            str(patch),
            "-o", tmp,
            "-n", name,
            "-g", "c",
            "-p", str(PD_DIR),                # abstraction search path
        ]
        result = subprocess.run(cmd, capture_output=True, text=True)
        print(result.stdout)
        if result.returncode != 0:
            print(result.stderr)
            fail("hvcc failed, see output above")

        generated = Path(tmp) / "c"
        if not generated.exists():
            fail(f"expected hvcc output at {generated}")

        # Clear old generated content, keep user-maintained files
        if lib_dir.exists():
            for child in lib_dir.iterdir():
                if child.name in KEEP_FILES:
                    continue
                if child.is_dir():
                    shutil.rmtree(child)
                else:
                    child.unlink()
        else:
            lib_dir.mkdir(parents=True)

        # Copy generated files directly into the library folder
        for item in generated.iterdir():
            dest = lib_dir / item.name
            if item.is_dir():
                shutil.copytree(item, dest)
            else:
                shutil.copy2(item, dest)

    stamp.write_text(current)


generate()